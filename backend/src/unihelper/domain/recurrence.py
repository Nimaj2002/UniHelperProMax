"""Recurrence rules: validation and expansion into sessions (research R4, R5).

Pure functions — no database access. Sessions are never stored; they are expanded on read
for the requested range, then single-session exceptions are applied.
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass
from datetime import date, datetime, time, timedelta
from typing import Protocol
from zoneinfo import ZoneInfo

from dateutil import rrule as du

WEEKDAYS: tuple[str, ...] = ("MO", "TU", "WE", "TH", "FR", "SA", "SU")
_WEEKDAY_NAMES = {
    "MO": "Mon",
    "TU": "Tue",
    "WE": "Wed",
    "TH": "Thu",
    "FR": "Fri",
    "SA": "Sat",
    "SU": "Sun",
}
_DU_DAYS = {
    "MO": du.MO,
    "TU": du.TU,
    "WE": du.WE,
    "TH": du.TH,
    "FR": du.FR,
    "SA": du.SA,
    "SU": du.SU,
}
MAX_INTERVAL = 8
MAX_COUNT = 500


class RuleError(ValueError):
    """Invalid rule; `field` is a JSON pointer into the class payload."""

    def __init__(self, field: str, code: str, message: str) -> None:
        super().__init__(message)
        self.field = field
        self.code = code
        self.message = message


@dataclass(frozen=True)
class Rule:
    freq: str  # "none" | "weekly"
    interval_weeks: int
    by_weekday: tuple[str, ...]
    end_kind: str  # "never" | "semester_end" | "until" | "count"
    until_date: date | None
    count: int | None
    start_date: date
    start_time: time
    end_time: time


class SegmentLike(Protocol):
    """The rule columns shared by `class_series` and (009) `event_series` rows."""

    @property
    def freq(self) -> str: ...
    @property
    def interval_weeks(self) -> int: ...
    @property
    def weekdays(self) -> tuple[str, ...]: ...
    @property
    def end_kind(self) -> str: ...
    @property
    def until_date(self) -> date | None: ...
    @property
    def count(self) -> int | None: ...
    @property
    def start_date(self) -> date: ...
    @property
    def start_time(self) -> time: ...
    @property
    def end_time(self) -> time: ...


def rule_of(s: SegmentLike) -> Rule:
    return Rule(
        freq=s.freq,
        interval_weeks=s.interval_weeks,
        by_weekday=s.weekdays,
        end_kind=s.end_kind,
        until_date=s.until_date,
        count=s.count,
        start_date=s.start_date,
        start_time=s.start_time,
        end_time=s.end_time,
    )


Links = tuple[tuple[str | None, str], ...]


@dataclass(frozen=True)
class ExceptionView:
    original_date: date
    kind: str  # "cancelled" | "modified"
    start_time: time | None
    end_time: time | None
    location: str | None
    version: int
    # 009 (events only): overrides, a moved date, and frozen occurrences (research R3, R4)
    title: str | None = None
    color: str | None = None
    links: Links | None = None
    moved_date: date | None = None
    detached: bool = False


@dataclass(frozen=True)
class SessionView:
    key: str
    lineage_id: str
    series_id: str
    date: date  # the day it takes place (a moved occurrence's `moved_date`)
    start: datetime
    end: datetime
    location: str | None
    status: str  # "upcoming" | "past"
    is_exception: bool
    exception_version: int | None
    # 009: None = use the series' value
    title: str | None = None
    color: str | None = None
    links: Links | None = None
    detached: bool = False


def session_key(lineage_id: str, day: date) -> str:
    return f"{lineage_id}:{day.isoformat()}"


def parse_session_key(key: str) -> tuple[str, date] | None:
    lineage, sep, raw = key.rpartition(":")
    if not sep or not lineage:
        return None
    try:
        return lineage, date.fromisoformat(raw)
    except ValueError:
        return None


def resolve_until(rule: Rule, semester_end: date | None) -> date | None:
    """Last possible date (inclusive) for until/semester_end rules; None otherwise."""
    if rule.end_kind == "until":
        return rule.until_date
    if rule.end_kind == "semester_end":
        return semester_end
    return None


def _rrule(rule: Rule, semester_end: date | None) -> du.rrule:
    dtstart = datetime.combine(rule.start_date, time())
    kwargs: dict[str, object] = {}
    until = resolve_until(rule, semester_end)
    if until is not None:
        kwargs["until"] = datetime.combine(until, time())
    elif rule.end_kind == "count" and rule.count:
        kwargs["count"] = rule.count
    return du.rrule(
        du.WEEKLY,
        interval=rule.interval_weeks,
        byweekday=[_DU_DAYS[d] for d in rule.by_weekday],
        dtstart=dtstart,
        wkst=du.MO,
        **kwargs,  # type: ignore[arg-type]
    )


def occurrence_dates(
    rule: Rule, semester_end: date | None, range_from: date, range_to: date
) -> list[date]:
    """Dates generated by the rule within [range_from, range_to] (inclusive)."""
    if rule.freq == "none":
        return [rule.start_date] if range_from <= rule.start_date <= range_to else []
    if rule.end_kind == "semester_end" and semester_end is None:
        return []
    r = _rrule(rule, semester_end)
    lo = datetime.combine(range_from, time())
    hi = datetime.combine(range_to, time())
    return [d.date() for d in r.between(lo, hi, inc=True)]


def generates(rule: Rule, semester_end: date | None, day: date) -> bool:
    return day in occurrence_dates(rule, semester_end, day, day)


def validate_rule(rule: Rule, semester_end: date | None) -> None:
    if rule.end_time <= rule.start_time:
        raise RuleError("/endTime", "invalid_time_range", "End time must be after the start time.")
    if rule.freq == "none":
        return
    if not (1 <= rule.interval_weeks <= MAX_INTERVAL):
        raise RuleError(
            "/recurrence/intervalWeeks",
            "invalid_interval",
            f"Repeat every 1 to {MAX_INTERVAL} weeks.",
        )
    if not rule.by_weekday:
        raise RuleError("/recurrence/byWeekday", "weekday_required", "Choose at least one weekday.")
    if any(d not in WEEKDAYS for d in rule.by_weekday):
        raise RuleError("/recurrence/byWeekday", "invalid_weekday", "Unknown weekday.")
    if rule.end_kind == "until":
        if rule.until_date is None:
            raise RuleError("/recurrence/end/untilDate", "until_required", "Choose an end date.")
        if rule.until_date < rule.start_date:
            raise RuleError(
                "/recurrence/end/untilDate",
                "series_ends_before_start",
                "The repetition ends before the class starts.",
            )
    elif rule.end_kind == "semester_end":
        if semester_end is None:
            raise RuleError(
                "/recurrence/end/kind",
                "semester_end_missing",
                "This semester has no end date. Add one, or choose another ending.",
            )
        if semester_end < rule.start_date:
            raise RuleError(
                "/recurrence/end/kind",
                "series_ends_before_start",
                "The semester ends before the class starts.",
            )
    elif rule.end_kind == "count":
        if rule.count is None or not (1 <= rule.count <= MAX_COUNT):
            raise RuleError(
                "/recurrence/end/count", "invalid_count", f"Repeat between 1 and {MAX_COUNT} times."
            )
    if rule.end_kind in ("until", "semester_end", "count"):
        end = resolve_until(rule, semester_end) or rule.start_date + timedelta(weeks=MAX_INTERVAL)
        if not occurrence_dates(rule, semester_end, rule.start_date, end):
            raise RuleError(
                "/recurrence", "no_sessions", "These settings don't produce any sessions."
            )


def occurrence_view(
    day: date,
    exc: ExceptionView | None,
    *,
    lineage_id: str,
    series_id: str,
    start_time: time,
    end_time: time,
    location: str | None,
    zone: ZoneInfo,
    now: datetime,
) -> SessionView:
    """One occurrence keyed by its original `day`, with a modified exception's overrides."""
    modified = exc is not None and exc.kind == "modified"
    mod = exc if modified else None
    st = (mod.start_time if mod else None) or start_time
    et = (mod.end_time if mod else None) or end_time
    loc = mod.location if mod and mod.location is not None else location
    shown = (mod.moved_date if mod else None) or day
    start = datetime.combine(shown, st, tzinfo=zone)
    end = datetime.combine(shown, et, tzinfo=zone)
    return SessionView(
        key=session_key(lineage_id, day),
        lineage_id=lineage_id,
        series_id=series_id,
        date=shown,
        start=start,
        end=end,
        location=loc,
        status="upcoming" if now < start else "past",
        is_exception=modified,
        exception_version=exc.version if exc is not None else None,
        title=mod.title if mod else None,
        color=mod.color if mod else None,
        links=mod.links if mod else None,
        detached=bool(mod and mod.detached),
    )


def expand(
    rule: Rule,
    *,
    lineage_id: str,
    series_id: str,
    semester_end: date | None,
    range_from: date,
    range_to: date,
    tz: str,
    now: datetime,
    exceptions: Sequence[ExceptionView] = (),
    location: str | None = None,
) -> list[SessionView]:
    """Occurrences of one segment shown within the range. A moved occurrence (009) is shown on
    its `moved_date` — included when that date is in range even if its original date is not —
    and keeps its original key."""
    zone = ZoneInfo(tz)
    by_date = {e.original_date: e for e in exceptions}
    days = occurrence_dates(rule, semester_end, range_from, range_to)
    moved_in = [
        e.original_date
        for e in exceptions
        if e.kind == "modified"
        and e.moved_date is not None
        and range_from <= e.moved_date <= range_to
        and not range_from <= e.original_date <= range_to
        and generates(rule, semester_end, e.original_date)
    ]
    out: list[SessionView] = []
    for day in sorted({*days, *moved_in}):
        exc = by_date.get(day)
        if exc is not None and exc.kind == "cancelled":
            continue
        view = occurrence_view(
            day,
            exc,
            lineage_id=lineage_id,
            series_id=series_id,
            start_time=rule.start_time,
            end_time=rule.end_time,
            location=location,
            zone=zone,
            now=now,
        )
        if range_from <= view.date <= range_to:
            out.append(view)
    out.sort(key=lambda v: (v.start, v.key))  # a moved occurrence may change places
    return out


def expand_detached(
    exceptions: Sequence[ExceptionView],
    generated: Callable[[date], bool],
    *,
    lineage_id: str,
    series_id: str,
    range_from: date,
    range_to: date,
    tz: str,
    now: datetime,
    start_time: time,
    end_time: time,
    location: str | None = None,
) -> list[SessionView]:
    """Frozen occurrences (009 research R4) that no segment of the lineage generates any more:
    `detached` modified exceptions stay scheduled on their own. `generated(day)` tells whether
    some segment still produces `day` (those are emitted by `expand`). The fallback times and
    location only fill gaps; a freeze stores the occurrence's full values."""
    zone = ZoneInfo(tz)
    out: list[SessionView] = []
    for e in sorted(exceptions, key=lambda x: x.original_date):
        if e.kind != "modified" or not e.detached or generated(e.original_date):
            continue
        view = occurrence_view(
            e.original_date,
            e,
            lineage_id=lineage_id,
            series_id=series_id,
            start_time=start_time,
            end_time=end_time,
            location=location,
            zone=zone,
            now=now,
        )
        if range_from <= view.date <= range_to:
            out.append(view)
    return out


def _days(days: Iterable[str]) -> str:
    return ", ".join(_WEEKDAY_NAMES[d] for d in WEEKDAYS if d in set(days))


def recurrence_summary(rule: Rule) -> str:
    if rule.freq == "none":
        return "Does not repeat"
    head = "Weekly" if rule.interval_weeks == 1 else f"Every {rule.interval_weeks} weeks"
    head += f" on {_days(rule.by_weekday)}"
    if rule.end_kind == "semester_end":
        return f"{head} until semester end"
    if rule.end_kind == "until" and rule.until_date:
        return f"{head} until {rule.until_date.day} {rule.until_date.strftime('%b %Y')}"
    if rule.end_kind == "count" and rule.count:
        return f"{head}, {rule.count} times"
    return head
