"""Recurrence rules: validation and expansion into sessions (research R4, R5).

Pure functions — no database access. Sessions are never stored; they are expanded on read
for the requested range, then single-session exceptions are applied.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from datetime import date, datetime, time, timedelta
from zoneinfo import ZoneInfo

from dateutil import rrule as du

WEEKDAYS: tuple[str, ...] = ("MO", "TU", "WE", "TH", "FR", "SA", "SU")
_WEEKDAY_NAMES = {
    "MO": "Mon",
    "TU": "Tue",
    "WE": "Wed",
    "TH": "Thu",
    "FR": "Fri",
    "SA": "Sat",
    "SU": "Sun",
}
_DU_DAYS = {
    "MO": du.MO,
    "TU": du.TU,
    "WE": du.WE,
    "TH": du.TH,
    "FR": du.FR,
    "SA": du.SA,
    "SU": du.SU,
}
MAX_INTERVAL = 8
MAX_COUNT = 500


class RuleError(ValueError):
    """Invalid rule; `field` is a JSON pointer into the class payload."""

    def __init__(self, field: str, code: str, message: str) -> None:
        super().__init__(message)
        self.field = field
        self.code = code
        self.message = message


@dataclass(frozen=True)
class Rule:
    freq: str  # "none" | "weekly"
    interval_weeks: int
    by_weekday: tuple[str, ...]
    end_kind: str  # "never" | "semester_end" | "until" | "count"
    until_date: date | None
    count: int | None
    start_date: date
    start_time: time
    end_time: time


@dataclass(frozen=True)
class ExceptionView:
    original_date: date
    kind: str  # "cancelled" | "modified"
    start_time: time | None
    end_time: time | None
    location: str | None
    version: int


@dataclass(frozen=True)
class SessionView:
    key: str
    lineage_id: str
    series_id: str
    date: date
    start: datetime
    end: datetime
    location: str | None
    status: str  # "upcoming" | "past"
    is_exception: bool
    exception_version: int | None


def session_key(lineage_id: str, day: date) -> str:
    return f"{lineage_id}:{day.isoformat()}"


def parse_session_key(key: str) -> tuple[str, date] | None:
    lineage, sep, raw = key.rpartition(":")
    if not sep or not lineage:
        return None
    try:
        return lineage, date.fromisoformat(raw)
    except ValueError:
        return None


def resolve_until(rule: Rule, semester_end: date | None) -> date | None:
    """Last possible date (inclusive) for until/semester_end rules; None otherwise."""
    if rule.end_kind == "until":
        return rule.until_date
    if rule.end_kind == "semester_end":
        return semester_end
    return None


def _rrule(rule: Rule, semester_end: date | None) -> du.rrule:
    dtstart = datetime.combine(rule.start_date, time())
    kwargs: dict[str, object] = {}
    until = resolve_until(rule, semester_end)
    if until is not None:
        kwargs["until"] = datetime.combine(until, time())
    elif rule.end_kind == "count" and rule.count:
        kwargs["count"] = rule.count
    return du.rrule(
        du.WEEKLY,
        interval=rule.interval_weeks,
        byweekday=[_DU_DAYS[d] for d in rule.by_weekday],
        dtstart=dtstart,
        wkst=du.MO,
        **kwargs,  # type: ignore[arg-type]
    )


def occurrence_dates(
    rule: Rule, semester_end: date | None, range_from: date, range_to: date
) -> list[date]:
    """Dates generated by the rule within [range_from, range_to] (inclusive)."""
    if rule.freq == "none":
        return [rule.start_date] if range_from <= rule.start_date <= range_to else []
    if rule.end_kind == "semester_end" and semester_end is None:
        return []
    r = _rrule(rule, semester_end)
    lo = datetime.combine(range_from, time())
    hi = datetime.combine(range_to, time())
    return [d.date() for d in r.between(lo, hi, inc=True)]


def generates(rule: Rule, semester_end: date | None, day: date) -> bool:
    return day in occurrence_dates(rule, semester_end, day, day)


def validate_rule(rule: Rule, semester_end: date | None) -> None:
    if rule.end_time <= rule.start_time:
        raise RuleError("/endTime", "invalid_time_range", "End time must be after the start time.")
    if rule.freq == "none":
        return
    if not (1 <= rule.interval_weeks <= MAX_INTERVAL):
        raise RuleError(
            "/recurrence/intervalWeeks",
            "invalid_interval",
            f"Repeat every 1 to {MAX_INTERVAL} weeks.",
        )
    if not rule.by_weekday:
        raise RuleError("/recurrence/byWeekday", "weekday_required", "Choose at least one weekday.")
    if any(d not in WEEKDAYS for d in rule.by_weekday):
        raise RuleError("/recurrence/byWeekday", "invalid_weekday", "Unknown weekday.")
    if rule.end_kind == "until":
        if rule.until_date is None:
            raise RuleError("/recurrence/end/untilDate", "until_required", "Choose an end date.")
        if rule.until_date < rule.start_date:
            raise RuleError(
                "/recurrence/end/untilDate",
                "series_ends_before_start",
                "The repetition ends before the class starts.",
            )
    elif rule.end_kind == "semester_end":
        if semester_end is None:
            raise RuleError(
                "/recurrence/end/kind",
                "semester_end_missing",
                "This semester has no end date. Add one, or choose another ending.",
            )
        if semester_end < rule.start_date:
            raise RuleError(
                "/recurrence/end/kind",
                "series_ends_before_start",
                "The semester ends before the class starts.",
            )
    elif rule.end_kind == "count":
        if rule.count is None or not (1 <= rule.count <= MAX_COUNT):
            raise RuleError(
                "/recurrence/end/count", "invalid_count", f"Repeat between 1 and {MAX_COUNT} times."
            )
    if rule.end_kind in ("until", "semester_end", "count"):
        end = resolve_until(rule, semester_end) or rule.start_date + timedelta(weeks=MAX_INTERVAL)
        if not occurrence_dates(rule, semester_end, rule.start_date, end):
            raise RuleError(
                "/recurrence", "no_sessions", "These settings don't produce any sessions."
            )


def expand(
    rule: Rule,
    *,
    lineage_id: str,
    series_id: str,
    semester_end: date | None,
    range_from: date,
    range_to: date,
    tz: str,
    now: datetime,
    exceptions: Sequence[ExceptionView] = (),
    location: str | None = None,
) -> list[SessionView]:
    zone = ZoneInfo(tz)
    by_date = {e.original_date: e for e in exceptions}
    out: list[SessionView] = []
    for day in occurrence_dates(rule, semester_end, range_from, range_to):
        exc = by_date.get(day)
        if exc is not None and exc.kind == "cancelled":
            continue
        modified = exc is not None and exc.kind == "modified"
        st = (exc.start_time if modified and exc and exc.start_time else None) or rule.start_time
        et = (exc.end_time if modified and exc and exc.end_time else None) or rule.end_time
        loc = exc.location if modified and exc and exc.location is not None else location
        start = datetime.combine(day, st, tzinfo=zone)
        end = datetime.combine(day, et, tzinfo=zone)
        out.append(
            SessionView(
                key=session_key(lineage_id, day),
                lineage_id=lineage_id,
                series_id=series_id,
                date=day,
                start=start,
                end=end,
                location=loc,
                status="upcoming" if now < start else "past",
                is_exception=modified,
                exception_version=exc.version if exc is not None else None,
            )
        )
    return out


def _days(days: Iterable[str]) -> str:
    return ", ".join(_WEEKDAY_NAMES[d] for d in WEEKDAYS if d in set(days))


def recurrence_summary(rule: Rule) -> str:
    if rule.freq == "none":
        return "Does not repeat"
    head = "Weekly" if rule.interval_weeks == 1 else f"Every {rule.interval_weeks} weeks"
    head += f" on {_days(rule.by_weekday)}"
    if rule.end_kind == "semester_end":
        return f"{head} until semester end"
    if rule.end_kind == "until" and rule.until_date:
        return f"{head} until {rule.until_date.day} {rule.until_date.strftime('%b %Y')}"
    if rule.end_kind == "count" and rule.count:
        return f"{head}, {rule.count} times"
    return head
