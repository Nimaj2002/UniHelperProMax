def view(deps: Deps, chat: Chat) -> dict[str, Any]:
    from unihelper.chat import attachments

    folder, doc = _load(deps, chat)
    files.ensure_transcript(deps.storage, folder, chat.stem, doc, label_of(deps.db, chat))
    availability = attachments.availability(deps.db, deps.user, doc)
    run_ids = {s.answer_id: s.id for s in deps.runs.active(deps.user.id) if s.chat_id == chat.id}
    folder_row = deps.db.get(SessionFolder, chat.session_folder_id)
    assert folder_row is not None
    ref = doc.get("model") or {}
    model_ok = chat.model_ref_id is not None and ref.get("modelId") == chat.model_ref_id
    return {
        **summary(chat),
        "session_key": folder_row.session_key,
        "model": {"endpoint_id": ref["endpointId"], "model_id": ref["modelId"]}
        if model_ok
        else None,
        "context": [_item_out(i, availability) for i in doc.get("context", [])],
        "turns": [
            {
                "id": turn["id"],
                "selected": turn.get("selected", 0),
                "versions": [
                    {
                        "id": v["id"],
                        "text": v.get("text", ""),
                        "created_at": v.get("createdAt", ""),
                        "attachments": [
                            _item_out(a, availability) for a in v.get("attachments", [])
                        ],
                        "note_snapshots": [
                            {"note_id": s["noteId"], "title": s["title"], "snapshot": s["snapshot"]}
                            for s in v.get("noteSnapshots", [])
                        ],
                        "answers": [_answer_out(a, run_ids) for a in v.get("answers", [])],
                        "selected_answer": v.get("selectedAnswer", 0),
                    }
                    for v in turn["versions"]
                ],
            }
            for turn in doc["turns"]
        ],
    }


