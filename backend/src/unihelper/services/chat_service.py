def _text_match(doc: dict[str, Any], needle: str) -> str | None:
    """A ±40 character snippet around the first match in any message of the chat (FR-062)."""
    lowered = needle.casefold()
    for turn in doc.get("turns", []):
        for version in turn.get("versions", []):
            texts = [version.get("text", "")] + [
                a.get("text", "") for a in version.get("answers", [])
            ]
            for text in texts:
                at = text.casefold().find(lowered)
                if at != -1:
                    start, end = max(0, at - 40), min(len(text), at + len(needle) + 40)
                    snippet = " ".join(text[start:end].split())
                    return ("…" if start else "") + snippet + ("…" if end < len(text) else "")
    return None


def list_chats(
    deps: Deps, session_key: str, q: str | None = None, where: str = "title"
) -> list[dict[str, Any]]:
    folder_row = _folder_of(deps.db, deps.user, session_key)
    if folder_row is None:
        return []
    rows = list(
        deps.db.scalars(
            select(Chat)
            .where(
                Chat.session_folder_id == folder_row.id,
                Chat.deleted_at.is_(None),
                Chat.kind == "chat",
            )
            .order_by(Chat.updated_at.desc(), Chat.id.desc())
        )
    )
    needle = (q or "").strip()
    if not needle:
        return [summary(c) for c in rows]
    if where == "title":
        return [summary(c) for c in rows if needle.casefold() in c.title.casefold()]
    out = []
    for chat in rows:
        try:
            _folder, doc = _load(deps, chat)
        except ApiError:
            continue
        match = _text_match(doc, needle)
        if match is not None or needle.casefold() in chat.title.casefold():
            out.append(summary(chat, match))
    return out


def rename(deps: Deps, chat: Chat, title: str) -> Chat:
    clean = " ".join(title.split())
    if not clean:
        raise ApiError(422, "title_required", "Enter a title.")
    with files.chat_lock(chat.id):
        folder, doc = _load(deps, chat)
        doc["title"] = clean
        chat.title = clean
        chat.file_hash = files.write(deps.storage, folder, chat.stem, doc, label_of(deps.db, chat))
        deps.db.flush()
    return chat


def update(deps: Deps, chat_id: str, version: int, body: Any) -> dict[str, Any]:
    from unihelper.api.deps import check_version

    chat = get_chat(deps.db, deps.user, chat_id)
    check_version(version, chat.version)
    if body.title is not None:
        rename(deps, chat, body.title)
    if body.model is not None or body.context is not None:
        with files.chat_lock(chat.id):
            folder, doc = _load(deps, chat)
            if body.model is not None:
                model, endpoint = _model(
                    deps.db, deps.user, body.model.endpoint_id, body.model.model_id
                )
                chat.model_ref_id = model.id
                chat.model_label = f"{endpoint.name} · {model.display_name}"
                doc["model"] = {
                    "endpointId": endpoint.id,
                    "modelId": model.id,
                    "label": chat.model_label,
                }
            if body.context is not None:  # removing items from the context list (FR-056)
                keep = {(i.kind, i.ref) for i in body.context}
                doc["context"] = [
                    c for c in doc.get("context", []) if (c.get("kind"), c.get("ref")) in keep
                ]
            chat.file_hash = files.write(
                deps.storage, folder, chat.stem, doc, label_of(deps.db, chat)
            )
    chat.updated_at = now_iso()
    deps.db.flush()
    return view(deps, chat)


def delete(deps: Deps, chat: Chat) -> None:
    """Soft delete for Undo (research R16); the sweep removes the files later."""
    chat.deleted_at = now_iso()
    chat.generating = False
    deps.db.flush()


def restore(deps: Deps, chat_id: str) -> dict[str, Any]:
    chat = get_chat(deps.db, deps.user, chat_id, include_deleted=True, kinds=CHAT_KINDS)
    if chat.deleted_at is None:
        return summary(chat)
    age = datetime.now(UTC) - datetime.fromisoformat(chat.deleted_at)
    if age.total_seconds() > UNDO_WINDOW_SECONDS:
        raise ApiError(410, "undo_expired", "This chat can no longer be restored.")
    chat.deleted_at = None
    deps.db.flush()
    return summary(chat)


# ───────────────────────────── drafts (FR-032) ─────────────────────────────


def _draft_out(draft: ChatDraft) -> dict[str, Any]:
    import json

    return {
        "chat_id": draft.chat_key or None,
        "text": draft.text,
        "attachments": json.loads(draft.attachments_json or "[]"),
        "updated_at": draft.updated_at,
    }


def get_drafts(deps: Deps, session_key: str) -> list[dict[str, Any]]:
    r = sfs.resolve(deps.db, deps.user, session_key)
    rows = deps.db.scalars(
        select(ChatDraft).where(
            ChatDraft.user_id == deps.user.id,
            ChatDraft.lineage_id == r.lineage_id,
            ChatDraft.original_date == r.day.isoformat(),
        )
    )
    return [_draft_out(d) for d in rows]


def put_draft(deps: Deps, session_key: str, body: Any) -> dict[str, Any]:
    """Last write wins, as one statement: two saves of the same draft racing each other (a
    debounced save and the flush on leaving the page) never fail."""
    import json

    from sqlalchemy import delete as sql_delete
    from sqlalchemy.dialects.sqlite import insert

    r = sfs.resolve(deps.db, deps.user, session_key)
    chat_key = body.chat_id or ""
    if chat_key and chat_key not in NEW_TEACHER_DRAFT_KEYS:  # 022: the new-teacher-chat boxes
        get_chat(deps.db, deps.user, chat_key, kinds=CHAT_KINDS)
    key = {
        "user_id": deps.user.id,
        "lineage_id": r.lineage_id,
        "original_date": r.day.isoformat(),
        "chat_key": chat_key,
    }
    attachments = [a.model_dump(by_alias=True, exclude_none=True) for a in body.attachments]
    stamp = now_iso()
    if not body.text and not attachments:
        deps.db.execute(
            sql_delete(ChatDraft).where(*(getattr(ChatDraft, k) == v for k, v in key.items()))
        )
        return {"chat_id": body.chat_id, "text": "", "attachments": [], "updated_at": stamp}
    values = {"text": body.text, "attachments_json": json.dumps(attachments), "updated_at": stamp}
    deps.db.execute(
        insert(ChatDraft)
        .values(**key, **values)
        .on_conflict_do_update(index_elements=list(key), set_=values)
    )
    return {
        "chat_id": body.chat_id,
        "text": body.text,
        "attachments": attachments,
        "updated_at": stamp,
    }


# ───────────────────────────── preflight and the context limit (US9) ─────────────────────────────


def check_context_limit(model: AiModel, request: ChatRequest) -> None:
    from unihelper.ai.estimate import request_tokens

    if model.context_limit and request_tokens(request) > model.context_limit:
        raise ApiError(
            409,
            "context_exceeded",
            "This conversation is larger than the model can take.",
            "Remove items from the context, or start a new chat.",
        )


def preflight(deps: Deps, body: Any) -> dict[str, Any]:
    """Per-item acceptance, the size estimate and the limits, before sending (FR-055/056)."""
    from unihelper.ai.estimate import text_tokens
    from unihelper.ai.styles import limits_out
    from unihelper.chat import attachments

    model, endpoint = _model(deps.db, deps.user, body.model.endpoint_id, body.model.model_id)
    context: list[dict[str, Any]] = []
    history = 0
    if body.chat_id:
        chat = get_chat(deps.db, deps.user, body.chat_id, kinds=CHAT_KINDS)
        _folder, doc = _load(deps, chat)
        context = list(doc.get("context", []))
        for turn in doc.get("turns", []):
            version = files.selected_version(turn)
            history += text_tokens(version.get("text", ""))
            answer = files.selected_answer(version)
            if answer:
                history += text_tokens(answer.get("text", ""))
    else:
        sfs.resolve(deps.db, deps.user, body.session_key)
    have = {(c.get("kind"), c.get("ref")) for c in context}
    for item in body.attachments:
        entry = {"kind": item.kind, "ref": item.ref}
        if item.pdf_mode:
            entry["pdfMode"] = item.pdf_mode
        if (item.kind, item.ref) in have:
            context = [
                entry if (c.get("kind"), c.get("ref")) == (item.kind, item.ref) else c
                for c in context
            ]
        else:
            context.append(entry)
    items = attachments.evaluate(deps.db, deps.storage, deps.user, context, model, endpoint)
    estimated = history + text_tokens(body.text) + sum(i.tokens for i in items)
    estimated += text_tokens(ai_settings_service.instructions(deps.db, deps.user.id) or "")
    return {
        "items": [
            {
                "kind": i.kind,
                "ref": i.ref,
                "pdf_mode": i.pdf_mode,
                "title": i.title,
                "mime": i.mime,
                "size": i.size,
                "available": i.available,
                "accepted": i.accepted,
                "reason": i.reason,
                "reason_code": i.reason_code,
                "text_fallback_available": i.text_fallback,
                "pdf_has_text": i.pdf_has_text,
                "estimated_tokens": i.tokens,
            }
            for i in items
        ],
        "estimated_tokens": estimated,
        "context_limit": model.context_limit,
        "over_limit": bool(model.context_limit and estimated > model.context_limit),
        "limits": limits_out(endpoint.style),
        "locality": endpoint.locality,
        "privacy_ack_required": endpoint.locality == "remote" and endpoint.privacy_ack_at is None,
    }


# ───────────────────────────── add an answer to a note (US10, FR-058) ─────────────────────────────


def append_answer(deps: Deps, chat_id: str, answer_id: str, target: Any) -> dict[str, Any]:
    """Append after the note's last character under `## Chat — <title> · <date>`, never
    overwriting (the transcript path, Principle I). A new note is created in the chat's session."""
    from unihelper.models import Note
    from unihelper.services import note_service

    chat = get_chat(deps.db, deps.user, chat_id)
    _folder, doc = _load(deps, chat)
    answer = files.find_answer(doc, answer_id)
    if answer is None:
        raise not_found("Answer")
    if answer.get("status") in ("queued", "streaming"):
        raise ApiError(409, "answer_incomplete", "Wait until the answer is complete.")
    if target.note_id:
        note = deps.db.get(Note, target.note_id)
        if note is None or note.user_id != deps.user.id:
            raise not_found("Note")
        note_id = note.id
    elif target.new_note_title:
        folder_row = deps.db.get(SessionFolder, chat.session_folder_id)
        assert folder_row is not None
        created = note_service.create_note(
            deps.db, deps.storage, deps.user, folder_row.session_key, target.new_note_title
        )
        note_id = created["id"]
    else:
        raise ApiError(422, "note_required", "Choose a note or name a new one.")
    when = _local_now(deps.user).strftime("%Y-%m-%d %H:%M")
    section = f"## Chat — {chat.title} · {when}\n\n{answer.get('text', '').strip()}\n"
    result = note_service.append_to_note(deps.db, deps.storage, deps.user, note_id, section)
    return {"note_id": note_id, **result}
