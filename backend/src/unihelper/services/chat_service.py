"""Chats of a session or event (014 US3/US4): files in the session folder, an index row each,
answers generated by runs (chat/runs.py).

A chat is created together with its first message, so an empty chat is never saved (FR-028).
Every send validates the model (enabled, not hidden), the Remote privacy acknowledgement
(FR-040), the text and the attachment count, writes the user message and an empty answer to the
chat file, and starts a run once the request's transaction has committed.
"""

