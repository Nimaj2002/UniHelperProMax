def get_chat(
    db: Session,
    user: User,
    chat_id: str,
    include_deleted: bool = False,
    kinds: tuple[str, ...] = ("chat",),
) -> Chat:
    """022: AI chat operations see only `kind = chat`; teacher chats answer 404 there."""
    chat = db.get(Chat, chat_id)
    if (
        chat is None
        or chat.user_id != user.id
        or chat.kind not in kinds
        or (chat.deleted_at and not include_deleted)
    ):
        raise not_found("Chat")
    folder = db.get(SessionFolder, chat.session_folder_id)
    if folder is None or folder.trash_entry_id is not None:
        raise not_found("Chat")
    return chat


def label_of(db: Session, chat: Chat) -> str:
    """ "Algorithms · Tue 14 Oct 2026" — where the chat belongs, for its transcript."""
    folder = db.get(SessionFolder, chat.session_folder_id)
    if folder is None:
        return "a session"
    day = folder.original_date.strftime("%a %d %b %Y")
    if folder.kind == "event":
        return f"{folder.title or 'Event'} · {day}"
    course = db.get(Course, folder.course_id) if folder.course_id else None
    return f"{course.name if course else 'Class'} · {day}"


def _model(
    db: Session, user: User, ref_endpoint: str, ref_model: str
) -> tuple[AiModel, AiEndpoint]:
    model = db.get(AiModel, ref_model)
    endpoint = db.get(AiEndpoint, ref_endpoint)
    if (
        model is None
        or endpoint is None
        or model.endpoint_id != endpoint.id
        or endpoint.user_id != user.id
        or model.hidden
        or not endpoint.enabled
    ):
        raise ApiError(
            409,
            "model_unavailable",
            "This model isn't available.",
            "Choose another model for this chat.",
        )
    return model, endpoint


def _labels(model: AiModel, endpoint: AiEndpoint) -> dict[str, str]:
    return {"endpointLabel": endpoint.name, "modelLabel": model.display_name}


def _privacy(endpoint: AiEndpoint) -> None:
    if endpoint.locality == "remote" and endpoint.privacy_ack_at is None:
        raise ApiError(
            409,
            "privacy_ack_required",
            f"Messages and attachments will be sent to {endpoint.base_url}.",
            "Confirm once that this endpoint may receive them.",
            extra={"endpointId": endpoint.id, "baseUrl": endpoint.base_url},
        )


def _check_message(body: SendMessage) -> None:
    if len(body.attachments) > MAX_ATTACHMENTS:
        raise ApiError(422, "too_many_attachments", "Attach at most 10 items to one message.")
    if not body.text.strip() and not body.attachments:
        raise ApiError(422, "empty_message", "Type a message or attach something to send.")


def _local_now(user: User) -> datetime:
    try:
        return datetime.now(UTC).astimezone(ZoneInfo(user.timezone))
    except Exception:  # an unknown zone name: UTC
        return datetime.now(UTC)


def _now(user: User) -> str:
    return _local_now(user).isoformat(timespec="seconds")


# ───────────────────────────── document pieces ─────────────────────────────


def _answer(user: User, model: AiModel, endpoint: AiEndpoint) -> dict[str, Any]:
    return {
        "id": new_id(),
        "status": "queued",
        "text": "",
        **_labels(model, endpoint),
        "locality": endpoint.locality,
        "endpointId": endpoint.id,
        "modelId": model.id,
        "startedAt": _now(user),
    }


def _merge_context(doc: dict[str, Any], attachments: list[ContextItemRef]) -> list[dict[str, Any]]:
    """Attachments of a message join the chat's context (deduplicated) and stay there."""
    context: list[dict[str, Any]] = doc.setdefault("context", [])
    have = {(c["kind"], c["ref"]) for c in context}
    added: list[dict[str, Any]] = []
    for item in attachments:
        key = (item.kind, item.ref)
        entry = {"kind": item.kind, "ref": item.ref, "title": item.ref, "addedAt": now_iso()}
        if item.pdf_mode:
            entry["pdfMode"] = item.pdf_mode
        if key not in have:
            context.append(entry)
            have.add(key)
        added.append(entry)
    return added


def _version(user: User, body: SendMessage, answer: dict[str, Any]) -> dict[str, Any]:
    return {
        "id": new_id(),
        "text": body.text,
        "createdAt": _now(user),
        "attachments": [],
        "noteSnapshots": [],
        "selectedAnswer": 0,
        "answers": [answer],
    }


# ───────────────────────────── starting a run ─────────────────────────────


def _context_parts(
    deps: Deps,
    folder: list[str],
    chat: Chat,
    doc: dict[str, Any],
    version: dict[str, Any],
    model: AiModel,
    endpoint: AiEndpoint,
) -> list[Part]:
    from unihelper.chat import attachments

    refs, notes = chat_context.take_note_snapshots(
        deps.db, deps.storage, deps.user, folder, chat.stem, doc.get("context", [])
    )
    version["noteSnapshots"] = refs
    parts: list[Part] = [*notes]
    parts += attachments.file_parts(
        deps.db, deps.storage, deps.user, folder, chat.stem, doc.get("context", []), model, endpoint
    )
    return parts


def _launch(
    deps: Deps,
    chat: Chat,
    doc: dict[str, Any],
    turn_index: int,
    answer: dict[str, Any],
    model: AiModel,
    endpoint: AiEndpoint,
    folder: list[str],
    context_parts: list[Part],
    build_request: Callable[[], ChatRequest] | None = None,
    configure: Callable[[Any], None] | None = None,
) -> dict[str, Any]:
    """Start a run for `answer`. 022: teacher chats pass their own request builder and a
    `configure(state)` that installs the block splitter before the run starts."""
    deps.runs.check_capacity(deps.user.id)
    try:
        cfg: EndpointConfig = ai_endpoint_service.config_for(deps.db, deps.store, endpoint)
    except KeyUnreadable as exc:
        raise ApiError(
            409,
            "key_unreadable",
            "The saved key of this endpoint can't be read on this computer.",
            "Enter the key again in Settings → AI.",
        ) from exc
    request: ChatRequest = (
        build_request()
        if build_request is not None
        else chat_context.build(deps.db, deps.user, doc, turn_index, model, context_parts)
    )
    check_context_limit(model, request)
    turn = doc["turns"][turn_index]
    run = ChatRun(user_id=deps.user.id, chat_id=chat.id, answer_id=answer["id"], status="queued")
    deps.db.add(run)
    deps.db.flush()
    folder_row = deps.db.get(SessionFolder, chat.session_folder_id)
    assert folder_row is not None
    state = deps.runs.prepare(
        run.id,
        deps.user.id,
        chat.id,
        folder_row.session_key,
        turn["id"],
        answer["id"],
        endpoint.id,
        {
            "runId": run.id,
            "chatId": chat.id,
            "turnId": turn["id"],
            "answerId": answer["id"],
            "endpointLabel": endpoint.name,
            "modelLabel": model.display_name,
            "locality": endpoint.locality,
        },
    )
    if configure is not None:
        configure(state)
    chat.generating = True
    chat.model_ref_id = model.id
    chat.model_label = f"{endpoint.name} · {model.display_name}"
    doc["model"] = {"endpointId": endpoint.id, "modelId": model.id, "label": chat.model_label}
    doc["updatedAt"] = _now(deps.user)
    chat.file_hash = files.write(deps.storage, folder, chat.stem, doc, label_of(deps.db, chat))
    chat.message_count = files.message_count(doc)
    chat.updated_at = now_iso()
    ai_settings_service.set_last_model(deps.db, deps.user, model.id)
    on_commit(deps.db, lambda: deps.runs.launch(state, cfg, request))
    on_rollback(deps.db, lambda: deps.runs.forget(run.id))
    deps.db.flush()
    return {
        "chat": summary(chat),
        "run_id": run.id,
        "turn_id": turn["id"],
        "answer_id": answer["id"],
    }


def _delete_draft(db: Session, user: User, folder: SessionFolder, chat_key: str) -> None:
    draft = db.get(
        ChatDraft, (user.id, folder.lineage_id, folder.original_date.isoformat(), chat_key)
    )
    if draft is not None:
        db.delete(draft)


def start_chat(deps: Deps, session_key: str, body: SendMessage) -> dict[str, Any]:
    _check_message(body)
    model, endpoint = _model(deps.db, deps.user, body.model.endpoint_id, body.model.model_id)
    _privacy(endpoint)
    deps.runs.check_capacity(deps.user.id)
    r = sfs.resolve(deps.db, deps.user, session_key)
    folder_row = sfs.get_or_create_folder(deps.db, deps.storage, deps.user, r)
    folder = sfs.folder_parts(deps.user, r, folder_row)
    taken = list(deps.db.scalars(select(Chat.stem).where(Chat.session_folder_id == folder_row.id)))
    title = files.title_from(body.text) if body.text.strip() else "New chat"
    stem = files.new_stem(_local_now(deps.user), title, taken)
    while deps.storage.exists(files.json_parts(folder, stem)):  # a file left on disk is kept
        taken.append(stem)
        stem = files.new_stem(_local_now(deps.user), title, taken)
    chat = Chat(
        id=new_id(),
        user_id=deps.user.id,
        session_folder_id=folder_row.id,
        stem=stem,
        title=title,
        model_label=f"{endpoint.name} · {model.display_name}",
    )
    deps.db.add(chat)
    deps.db.flush()
    answer = _answer(deps.user, model, endpoint)
    version = _version(deps.user, body, answer)
    doc: dict[str, Any] = {
        "format": files.FORMAT,
        "id": chat.id,
        "title": title,
        "createdAt": _now(deps.user),
        "updatedAt": _now(deps.user),
        "context": [],
        "turns": [{"id": new_id(), "selected": 0, "versions": [version]}],
    }
    version["attachments"] = _merge_context(doc, body.attachments)
    parts = _context_parts(deps, folder, chat, doc, version, model, endpoint)
    on_rollback(deps.db, lambda: _remove_files(deps.storage, folder, stem))
    _delete_draft(deps.db, deps.user, folder_row, "")
    return _launch(deps, chat, doc, 0, answer, model, endpoint, folder, parts)


def _remove_files(storage: StorageService, folder: list[str], stem: str) -> None:
    for parts in (files.json_parts(folder, stem), files.md_parts(folder, stem)):
        try:
            storage.path_for(parts).unlink(missing_ok=True)
        except OSError:  # pragma: no cover - best effort compensation
            pass


def _load(deps: Deps, chat: Chat) -> tuple[list[str], dict[str, Any]]:
    _user, folder = chat_location(deps.db, chat)
    try:
        return folder, files.read(deps.storage, folder, chat.stem)
    except files.ChatFileUnreadable as exc:
        raise ApiError(
            409,
            "chat_file_unreadable",
            "This chat's file can't be read.",
            f"The file {exc.path} was changed outside the app. It is left as it is.",
        ) from exc


def _no_active_run(deps: Deps, chat: Chat) -> None:
    if deps.runs.active_for_chat(chat.id) is not None:
        raise ApiError(409, "run_active", "An answer is still being generated in this chat.")


def send(deps: Deps, chat_id: str, body: SendMessage) -> dict[str, Any]:
    chat = get_chat(deps.db, deps.user, chat_id)
    _check_message(body)
    _no_active_run(deps, chat)
    model, endpoint = _model(deps.db, deps.user, body.model.endpoint_id, body.model.model_id)
    _privacy(endpoint)
    with files.chat_lock(chat.id):
        folder, doc = _load(deps, chat)
        answer = _answer(deps.user, model, endpoint)
        version = _version(deps.user, body, answer)
        version["attachments"] = _merge_context(doc, body.attachments)
        doc["turns"].append({"id": new_id(), "selected": 0, "versions": [version]})
        parts = _context_parts(deps, folder, chat, doc, version, model, endpoint)
        folder_row = deps.db.get(SessionFolder, chat.session_folder_id)
        assert folder_row is not None
        _delete_draft(deps.db, deps.user, folder_row, chat.id)
        return _launch(
            deps, chat, doc, len(doc["turns"]) - 1, answer, model, endpoint, folder, parts
        )


def _turn_index(doc: dict[str, Any], turn_id: str) -> int:
    for i, turn in enumerate(doc["turns"]):
        if turn["id"] == turn_id:
            return i
    raise not_found("Message")


def regenerate(deps: Deps, chat_id: str, turn_id: str, model_ref: Any | None) -> dict[str, Any]:
    """A new answer version for the selected user version (clarification Q3); also Retry."""
    chat = get_chat(deps.db, deps.user, chat_id)
    _no_active_run(deps, chat)
    with files.chat_lock(chat.id):
        folder, doc = _load(deps, chat)
        index = _turn_index(doc, turn_id)
        if model_ref is not None:
            model, endpoint = _model(deps.db, deps.user, model_ref.endpoint_id, model_ref.model_id)
        else:
            ref = doc.get("model") or {}
            model, endpoint = _model(
                deps.db, deps.user, ref.get("endpointId", ""), ref.get("modelId", "")
            )
        _privacy(endpoint)
        version = files.selected_version(doc["turns"][index])
        answer = _answer(deps.user, model, endpoint)
        version.setdefault("answers", []).append(answer)
        version["selectedAnswer"] = len(version["answers"]) - 1
        parts = (
            _context_parts(deps, folder, chat, doc, version, model, endpoint)
            if index == len(doc["turns"]) - 1
            else []
        )
        return _launch(deps, chat, doc, index, answer, model, endpoint, folder, parts)


def edit(deps: Deps, chat_id: str, turn_id: str, body: SendMessage) -> dict[str, Any]:
    """Edit and resend the last user message as a new version (clarification Q5)."""
    chat = get_chat(deps.db, deps.user, chat_id)
    _check_message(body)
    _no_active_run(deps, chat)
    model, endpoint = _model(deps.db, deps.user, body.model.endpoint_id, body.model.model_id)
    _privacy(endpoint)
    with files.chat_lock(chat.id):
        folder, doc = _load(deps, chat)
        index = _turn_index(doc, turn_id)
        if index != len(doc["turns"]) - 1:
            raise ApiError(409, "not_last_turn", "Only the last message can be edited.")
        turn = doc["turns"][index]
        answer = _answer(deps.user, model, endpoint)
        version = _version(deps.user, body, answer)
        version["attachments"] = _merge_context(doc, body.attachments)
        turn["versions"].append(version)
        turn["selected"] = len(turn["versions"]) - 1
        parts = _context_parts(deps, folder, chat, doc, version, model, endpoint)
        return _launch(deps, chat, doc, index, answer, model, endpoint, folder, parts)


def select_versions(
    deps: Deps, chat_id: str, turn_id: str, version: int, answer: int
) -> dict[str, Any]:
    chat = get_chat(deps.db, deps.user, chat_id)
    _no_active_run(deps, chat)
    with files.chat_lock(chat.id):
        folder, doc = _load(deps, chat)
        turn = doc["turns"][_turn_index(doc, turn_id)]
        if version >= len(turn["versions"]):
            raise ApiError(422, "no_such_version", "That version doesn't exist.")
        turn["selected"] = version
        chosen = turn["versions"][version]
        if answer >= max(1, len(chosen.get("answers", []))):
            raise ApiError(422, "no_such_version", "That version doesn't exist.")
        chosen["selectedAnswer"] = answer
        doc["updatedAt"] = _now(deps.user)
        chat.file_hash = files.write(deps.storage, folder, chat.stem, doc, label_of(deps.db, chat))
        chat.message_count = files.message_count(doc)
        deps.db.flush()
    return view(deps, chat)


